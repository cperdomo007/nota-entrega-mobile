CREATE TABLE IF NOT EXISTS mobile_users (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(254) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  passwordHash VARCHAR(255) NOT NULL,
  role ENUM('user','admin') NOT NULL DEFAULT 'user',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  failedAttempts INT NOT NULL DEFAULT 0,
  lockedUntil DATETIME(3) NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS mobile_sessions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  userId INT NOT NULL,
  accessHash CHAR(64) CHARACTER SET ascii NOT NULL UNIQUE,
  refreshHash CHAR(64) CHARACTER SET ascii NOT NULL UNIQUE,
  accessExpiresAt DATETIME(3) NOT NULL,
  refreshExpiresAt DATETIME(3) NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT mobile_session_user FOREIGN KEY (userId) REFERENCES mobile_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS mobile_note_requests (
  userId INT NOT NULL,
  requestKey VARCHAR(96) CHARACTER SET ascii NOT NULL,
  payloadHash CHAR(64) CHARACTER SET ascii NOT NULL,
  noteId INT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (userId,requestKey),
  CONSTRAINT mobile_request_user FOREIGN KEY (userId) REFERENCES mobile_users(id)
) ENGINE=InnoDB;
